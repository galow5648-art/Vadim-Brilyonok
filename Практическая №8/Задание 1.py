# Задача: от начала суток прошла 1/5 того времени, что осталось до конца суток
# Значит, прошла 1 часть, а осталось 5 таких же частей
parts_total = 1 + 5

# В сутках 24 часа, делим их на 6 равных частей
# Одна часть это сколько прошло от начала суток
hours = 24 // parts_total

print("Сейчас", hours, "ч 0 мин")
